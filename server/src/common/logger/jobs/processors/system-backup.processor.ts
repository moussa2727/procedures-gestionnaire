// jobs/processors/system-backup.processor.ts
import { OnWorkerEvent, Processor, WorkerHost } from '@nestjs/bullmq';
import { Job } from 'bullmq';
import { Logger, OnModuleInit } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { PrismaService } from '@/prisma/prisma.service';
import * as fs from 'fs';
import * as path from 'path';
import { Client } from 'pg';

@Processor('system-backup')
export class SystemBackupProcessor extends WorkerHost implements OnModuleInit {
  private readonly logger = new Logger(SystemBackupProcessor.name);
  private readonly backupDir: string;

  constructor(
    private configService: ConfigService,
    private prisma: PrismaService,
  ) {
    super();
    const baseDir =
      process.env.NODE_ENV === 'production' ? '/tmp' : process.cwd();
    this.backupDir = path.join(baseDir, 'backups');
    this.ensureBackupDir();
  }

  onModuleInit(): void {
    this.logger.log(
      'SystemBackupProcessor instancie et pret a consommer la queue "system-backup"',
    );
  }

  @OnWorkerEvent('active')
  onActive(job: Job): void {
    this.logger.log(`Worker actif sur le job "${job.name}" (id=${job.id})`);
  }

  @OnWorkerEvent('completed')
  onCompleted(job: Job): void {
    this.logger.log(
      `Job "${job.name}" (id=${job.id}) marque comme complete par le worker`,
    );
  }

  @OnWorkerEvent('failed')
  onFailed(job: Job, error: Error): void {
    this.logger.error(
      `Job "${job?.name}" (id=${job?.id}) marque comme echoue par le worker : ${error?.message}`,
    );
  }

  @OnWorkerEvent('error')
  onError(error: Error): void {
    this.logger.error(
      `Erreur worker sur la queue "system-backup" : ${error?.message}`,
    );
  }

  private ensureBackupDir() {
    try {
      if (!fs.existsSync(this.backupDir)) {
        fs.mkdirSync(this.backupDir, { recursive: true });
        this.logger.log(`Created backup directory: ${this.backupDir}`);
      }
    } catch (error) {
      this.logger.error(`Failed to create backup directory: ${error}`);
      const fallbackDir = '/tmp/backups';
      if (!fs.existsSync(fallbackDir)) {
        fs.mkdirSync(fallbackDir, { recursive: true });
      }
      Object.assign(this, {
        backupDir: fallbackDir,
      });
      this.logger.warn(`Using fallback backup directory: ${fallbackDir}`);
    }
  }

  async process(job: Job): Promise<any> {
    this.logger.log(
      `Traitement du job "${job.name}" demarre (id=${job.id}, tentative=${job.attemptsMade + 1})`,
    );

    try {
      if (job.name === 'backup-database') {
        const result = await this.backupDatabase();
        if (result?.success === false) {
          this.logger.error(
            `Traitement du job "${job.name}" termine en echec (id=${job.id}) : ${result.error}`,
          );
        } else {
          this.logger.log(
            `Traitement du job "${job.name}" termine avec succes (id=${job.id})`,
          );
        }
        return result;
      }
      this.logger.warn(
        `Job "${job.name}" recu mais aucun handler correspondant (id=${job.id})`,
      );
      return null;
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Erreur inconnue';
      this.logger.error(
        `Echec du traitement du job "${job.name}" (id=${job.id}) : ${message}`,
      );
      throw err;
    }
  }

  private async backupDatabase() {
    const startTime = Date.now();
    const date = new Date();
    const timestamp = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}_${date.getHours()}-${date.getMinutes()}`;
    const backupFile = path.join(this.backupDir, `backup-${timestamp}.sql`);
    const statsFile = path.join(this.backupDir, `backup-${timestamp}.json`);

    let pgClient: Client | null = null;

    try {
      const databaseUrl = this.configService.get<string>('DATABASE_URL');

      if (!databaseUrl) {
        throw new Error('DATABASE_URL is not defined in environment variables');
      }

      pgClient = new Client({ connectionString: databaseUrl });
      await pgClient.connect();

      this.logger.log('Connected to database for backup');

      const tables = await this.getTables(pgClient);
      const backupContent: string[] = [];

      backupContent.push('-- Database backup generated by Paname Consulting');
      backupContent.push(`-- Date: ${new Date().toISOString()}`);
      backupContent.push('');

      for (const table of tables) {
        this.logger.debug(`Backing up table: ${table}`);
        backupContent.push(`-- Table: ${table}`);
        backupContent.push(await this.exportTableData(pgClient, table));
        backupContent.push('');
      }

      fs.writeFileSync(backupFile, backupContent.join('\n'));

      const stats = await this.generateBackupStats();
      fs.writeFileSync(statsFile, JSON.stringify(stats, null, 2));

      const backupSize = fs.statSync(backupFile).size;
      const duration = Date.now() - startTime;

      this.logger.log(
        `Database backup completed: ${backupFile} (${(backupSize / 1024 / 1024).toFixed(2)} MB) in ${duration}ms`,
      );

      await this.cleanupOldBackups();

      return {
        success: true,
        file: backupFile,
        size: backupSize,
        duration,
        stats,
      };
    } catch (error) {
      this.logger.error(`Database backup failed: ${(error as Error).message}`);
      return { success: false, error: (error as Error).message };
    } finally {
      if (pgClient) {
        await pgClient.end();
      }
    }
  }

  private async getTables(client: Client): Promise<string[]> {
    const result = await client.query(`
      SELECT tablename 
      FROM pg_tables 
      WHERE schemaname = 'public'
      ORDER BY tablename
    `);
    return result.rows.map((row: { tablename: string }) => row.tablename);
  }

  private async exportTableData(
    client: Client,
    tableName: string,
  ): Promise<string> {
    const result = await client.query(`SELECT * FROM "${tableName}"`);
    const rows = result.rows;

    if (rows.length === 0) {
      return `-- No data in ${tableName}`;
    }

    const columns = Object.keys(rows[0]);
    const values = rows.map((row: Record<string, unknown>) => {
      const cols = columns.map((col) => {
        const val = row[col];
        if (val === null) return 'NULL';
        if (typeof val === 'object')
          return `'${JSON.stringify(val).replace(/'/g, "''")}'`;
        return `'${String(val).replace(/'/g, "''")}'`;
      });
      return `(${cols.join(', ')})`;
    });

    return `INSERT INTO "${tableName}" ("${columns.join('", "')}") VALUES\n  ${values.join(',\n  ')};`;
  }

  private async generateBackupStats() {
    const [userCount, rendezvousCount, procedureCount, destinationCount] =
      await Promise.all([
        this.prisma.user.count(),
        this.prisma.rendezVous.count(),
        this.prisma.procedure.count(),
        this.prisma.destination.count(),
      ]);

    return {
      timestamp: new Date().toISOString(),
      counts: {
        users: userCount,
        rendezvous: rendezvousCount,
        procedures: procedureCount,
        destinations: destinationCount,
      },
    };
  }

  private cleanupOldBackups() {
    const sevenDaysAgo = Date.now() - 7 * 24 * 60 * 60 * 1000;
    const files = fs.readdirSync(this.backupDir);
    let deleted = 0;

    for (const file of files) {
      if (
        file.startsWith('backup-') &&
        (file.endsWith('.sql') || file.endsWith('.json'))
      ) {
        const filePath = path.join(this.backupDir, file);
        const stats = fs.statSync(filePath);
        if (stats.mtimeMs < sevenDaysAgo) {
          fs.unlinkSync(filePath);
          deleted++;
          this.logger.debug(`Deleted old backup: ${file}`);
        }
      }
    }

    if (deleted > 0) {
      this.logger.log(`Cleaned up ${deleted} old backup files`);
    }
  }
}
